"""Index every run under results/: results/catalog.csv and results/README.md.

    python scripts/catalog_results.py

Layout: results/<sample>/<run>/ for estimation runs (written by run_grid.py)
and results/<sample>/profiles/<grid>/<model>/<selection>/ for profile
likelihoods. A one-line about.txt in a sample or run folder describes it;
everything else is read from run_protocol.json, protocol.json and meta.json.
"""
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from estimation.config import BOUNDS, RESULTS  # noqa: E402
from estimation.spec import CANON  # noqa: E402


def about(folder):
    path = folder / "about.txt"
    return path.read_text().strip() if path.exists() else ""


def read_json(path):
    return json.loads(path.read_text()) if path.exists() else {}


def bound_text(protocol, pws):
    """Lambda and weighting bounds of the run, e.g. 'lambda<=20; tk gamma>=0.28'."""
    tables = protocol.get("inputs", {}).get("bounds")
    texts = []
    for pw in pws:
        weight = CANON[pw]["PALPHA" if pw == "prelec" else "GAM"]
        table = tables[pw] if tables else BOUNDS[pw]
        lam = protocol.get("lambda_bound", table[CANON[pw]["LAM"]])
        low = protocol.get("weight_bound", table[weight])[0] if pw == "tk" else table[weight][0]
        texts.append(f"{pw}: lambda<={lam[1]:g}, {'gamma' if pw == 'tk' else 'alpha'}>={low:g}")
    return "; ".join(dict.fromkeys(texts))


def exclusion_text(protocol):
    filters = protocol.get("sample_filters")
    if filters:
        rules = ([f"top-endpoint share >= {filters['exclude_endpoint']}"] if filters.get("exclude_endpoint") else []) + \
                [f"listed in {name}" for name in filters.get("exclude_files", {})]
        return f"{' + '.join(rules)} ({filters['n_excluded']} excluded)" if rules else "none"
    if "exclusion" in protocol:
        return f"{protocol['exclusion']} ({protocol.get('n_excluded', '?')} excluded)"
    return "none"


def grid_row(run, sample):
    metas = pd.DataFrame([read_json(path) for path in run.glob("test*/meta.json")])
    metas = metas[metas.status == "done"]
    protocol = read_json(run / "run_protocol.json")
    pws = sorted(metas.pw.unique())
    fitted = metas[metas.equivalent_to.isna()] if "equivalent_to" in metas else metas
    best = {test: group.sort_values("bic").config_id.iloc[0] for test, group in fitted.groupby("test")}
    stamps = metas.timestamp.dropna().sort_values() if "timestamp" in metas else pd.Series(dtype=str)
    return dict(sample=sample.name, run=run.name if run != sample else ".", kind="grid", participants=int(metas.n_subjects.iloc[0]),
                ces=int(metas.n_obs.iloc[0]), models=len(metas),
                tests=", ".join(f"{test} x{count}" for test, count in metas.test.value_counts().sort_index().items()),
                weighting=", ".join(pws), exclusion=exclusion_text(protocol), bounds=bound_text(protocol, pws),
                seeds=len(protocol.get("seeds", [])) or "", finished=str(stamps.iloc[-1])[:10] if len(stamps) else "",
                best_test3=best.get("test3", ""), best_test1=best.get("test1", ""), best_test2=best.get("test2", ""),
                about=about(run))


def profile_rows(profiles):
    rows = []
    for manifest in sorted(profiles.glob("**/protocol.json")):
        protocol = read_json(manifest)
        for job in protocol.get("jobs", []):
            target = job["target"]
            folder = manifest.parent / f"cluster_{target['cluster'] + 1}_{target['name']}"
            rows.append(dict(sample=profiles.parent.name, run=str(manifest.parent.relative_to(profiles.parent)),
                             kind="profile", models=1, tests=Path(protocol["result"]).parent.name,
                             weighting=protocol["spec"]["pw"],
                             about=f"{target['name']} of cluster {target['cluster'] + 1}, {len(job['grid'])} grid points, "
                                   + ("finished" if (folder / "profile.csv").exists() else "unfinished")))
    return rows


def main():
    rows = []
    for sample in sorted(path for path in RESULTS.iterdir() if path.is_dir()):
        runs = [sample] if any(sample.glob("test*/meta.json")) else sorted(path for path in sample.iterdir() if path.is_dir())
        for run in runs:
            if any(run.glob("test*/meta.json")):
                rows.append(grid_row(run, sample))
            elif run.name == "profiles":
                rows += profile_rows(run)
    catalog = pd.DataFrame(rows).astype({"participants": "Int64", "ces": "Int64"})
    catalog.to_csv(RESULTS / "catalog.csv", index=False)

    lines = ["# Results", "", "Generated by `python scripts/catalog_results.py`; do not edit by hand.",
             "Describe a sample or run in a one-line `about.txt` inside its folder.", ""]
    for sample, group in catalog.groupby("sample", sort=False):
        lines += [f"## {sample}", "", about(RESULTS / sample) or "", ""]
        grids = group[group.kind == "grid"]
        if len(grids):
            lines += ["| Run | Participants / CEs | Models | Weighting and bounds | Excluded | Lowest BIC (Test 3 / Test 1) | About |",
                      "|---|---|---|---|---|---|---|"]
            for _, row in grids.iterrows():
                lines.append(f"| `{row.run}` | {int(row.participants):,} / {int(row.ces):,} | {row.models} ({row.tests}) | {row.bounds} | "
                             f"{row.exclusion} | {row.best_test3 or '-'} / {row.best_test1 or '-'} | {row.about} |")
            lines.append("")
        profiles = group[group.kind == "profile"]
        if len(profiles):
            lines += ["| Profile | Model | About |", "|---|---|---|"]
            lines += [f"| `{row.run}` | {row.tests} | {row.about} |" for _, row in profiles.iterrows()]
            lines.append("")
    (RESULTS / "README.md").write_text("\n".join(lines))
    print(f"Indexed {len(catalog)} runs: {RESULTS / 'catalog.csv'}, {RESULTS / 'README.md'}")


if __name__ == "__main__":
    main()
